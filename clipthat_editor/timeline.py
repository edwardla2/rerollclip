"""Reroll's editing timeline: the structured description of an edit.

Creative decisions (director.py) produce a Timeline; rendering (compositor.py) executes it.
Everything is plain data that round-trips through JSON, so an edit can be inspected, edited
by hand, or generated by another planner.

Times:
  * Clip.keys map *source* seconds (from the clip's src_in) to *local output* seconds
    (from the clip's out_start), with a speed on each side of every key. Between keys the
    mapping is a monotone cubic (Hermite), so speed changes are smooth curves, while a key
    can still change speed instantly (a "snap" into slow motion) when its two sides differ.
  * Camera curves are in the clip's local output time.
  * Master effects, text and sound effects are in master output time.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
import json
import math
from pathlib import Path
from typing import Any

EASES = ("linear", "smooth", "in", "out", "out3", "hold")


def ease(kind: str, u: float) -> float:
    u = min(1.0, max(0.0, u))
    if kind == "smooth":
        return u * u * (3 - 2 * u)
    if kind == "in":
        return u * u
    if kind == "out":
        return 1 - (1 - u) ** 2
    if kind == "out3":
        return 1 - (1 - u) ** 3
    if kind == "hold":
        return 0.0 if u < 1 else 1.0
    return u


def _ease_expr(kind: str, u: str) -> str:
    """The same easing as an FFmpeg expression of u (already clipped to 0..1)."""
    if kind == "smooth":
        return f"({u})*({u})*(3-2*({u}))"
    if kind == "in":
        return f"({u})*({u})"
    if kind == "out":
        return f"(1-(1-({u}))*(1-({u})))"
    if kind == "out3":
        return f"(1-pow(1-({u})\\,3))"
    if kind == "hold":
        return f"gte({u}\\,1)"
    return f"({u})"


@dataclass
class Curve:
    """Keyframes [[t, value, ease], ...]: `ease` shapes the move *into* that key."""
    keys: list[list[Any]] = field(default_factory=list)

    @classmethod
    def const(cls, v: float) -> "Curve":
        return cls([[0.0, v, "linear"]])

    def add(self, t: float, v: float, kind: str = "linear") -> "Curve":
        assert kind in EASES, kind
        self.keys.append([round(t, 4), round(v, 5), kind])
        self.keys.sort(key=lambda k: k[0])
        return self

    def at(self, t: float) -> float:
        if not self.keys:
            return 0.0
        if t <= self.keys[0][0]:
            return self.keys[0][1]
        for (t0, v0, _), (t1, v1, kind) in zip(self.keys, self.keys[1:]):
            if t <= t1:
                return v0 + (v1 - v0) * ease(kind, (t - t0) / (t1 - t0) if t1 > t0 else 1.0)
        return self.keys[-1][1]

    def is_const(self, v: float | None = None) -> bool:
        vals = {round(k[1], 6) for k in self.keys}
        return len(vals) <= 1 and (v is None or not vals or abs(next(iter(vals)) - v) < 1e-9)

    def expr(self, var: str = "t") -> str:
        """Piecewise FFmpeg expression (commas escaped for use inside a quoted option)."""
        if not self.keys:
            return "0"
        out = f"{self.keys[-1][1]:.5f}"
        pairs = list(zip(self.keys, self.keys[1:]))
        for (t0, v0, _), (t1, v1, kind) in reversed(pairs):
            if t1 <= t0:
                continue
            u = f"clip(({var}-{t0:.4f})/{t1 - t0:.4f}\\,0\\,1)"
            piece = f"({v0:.5f}+{v1 - v0:.5f}*{_ease_expr(kind, u)})"
            out = f"if(lt({var}\\,{t1:.4f})\\,{piece}\\,{out})"
        return f"if(lt({var}\\,{self.keys[0][0]:.4f})\\,{self.keys[0][1]:.5f}\\,{out})"


@dataclass
class TimeKey:
    src: float              # seconds from the clip's src_in
    out: float              # seconds from the clip's out_start
    speed_in: float = 1.0   # playback speed arriving at this key (0.25 = quarter speed)
    speed_out: float = 1.0  # playback speed leaving it


@dataclass
class Shake:
    t: float                # local output time it hits
    amp: float = 0.01       # share of the frame width
    decay: float = 0.25     # seconds to die out
    freq: float = 11.0      # oscillations a second


@dataclass
class Clip:
    label: str
    src_in: float
    src_out: float
    out_start: float
    keys: list[TimeKey]
    zoom: Curve = field(default_factory=lambda: Curve.const(1.0))
    rot: Curve = field(default_factory=lambda: Curve.const(0.0))     # degrees
    pan_x: Curve = field(default_factory=lambda: Curve.const(0.0))   # share of frame width
    pan_y: Curve = field(default_factory=lambda: Curve.const(0.0))
    shakes: list[Shake] = field(default_factory=list)
    motion_blur: int = 0        # source frames blended (shutter) before retiming; 0 = off
    interpolate: bool = True    # synthesize in-between frames (smooth slow motion / 60 fps)
    game_gain: float = 1.0

    @property
    def out_dur(self) -> float:
        return self.keys[-1].out

    @property
    def out_end(self) -> float:
        return self.out_start + self.out_dur

    def segments(self) -> list[tuple[TimeKey, TimeKey, float, float]]:
        """Hermite pieces (a, b, m0, m1) with slopes d(out)/d(src), limited so every piece
        stays monotone (Fritsch-Carlson): time never runs backwards or stalls."""
        out = []
        for a, b in zip(self.keys, self.keys[1:]):
            h = b.src - a.src
            d = (b.out - a.out) / h
            m0, m1 = 1 / a.speed_out, 1 / b.speed_in
            al, be = m0 / d, m1 / d
            r = math.hypot(al, be)
            if r > 3:
                m0, m1 = m0 * 3 / r, m1 * 3 / r
            out.append((a, b, m0, m1))
        return out

    def out_at(self, src: float) -> float:
        """Local output time of a source time (seconds from src_in)."""
        for a, b, m0, m1 in self.segments():
            if src <= b.src:
                h = b.src - a.src
                u = (src - a.src) / h
                h00, h10 = 2 * u ** 3 - 3 * u ** 2 + 1, u ** 3 - 2 * u ** 2 + u
                h01, h11 = -2 * u ** 3 + 3 * u ** 2, u ** 3 - u ** 2
                return h00 * a.out + h10 * h * m0 + h01 * b.out + h11 * h * m1
        return self.keys[-1].out

    def chunks(self, slow: float = 0.9) -> list[tuple[int, int, bool]]:
        """Runs of key segments (first key index, last key index, slow?) where the footage
        plays below `slow` speed or not, so slow motion can be treated on its own."""
        runs: list[list] = []
        for i, (a, b) in enumerate(zip(self.keys, self.keys[1:])):
            is_slow = min(a.speed_out, b.speed_in) < slow
            if runs and runs[-1][2] == is_slow:
                runs[-1][1] = i + 1
            else:
                runs.append([i, i + 1, is_slow])
        return [tuple(r) for r in runs]

    def speed_at(self, src: float, eps: float = 1e-3) -> float:
        return 2 * eps / max(1e-9, self.out_at(src + eps) - self.out_at(src - eps))

    def setpts_expr(self, var: str = "T") -> str:
        """Output time from source time `var` (seconds from src_in), as FFmpeg setpts input."""
        T = var
        out = f"{self.keys[-1].out:.6f}"
        for a, b, m0, m1 in reversed(self.segments()):
            h = b.src - a.src
            u = f"(({T}-{a.src:.6f})/{h:.6f})"
            c3 = 2 * a.out + h * m0 - 2 * b.out + h * m1
            c2 = -3 * a.out - 2 * h * m0 + 3 * b.out - h * m1
            c1 = h * m0
            poly = f"({a.out:.6f}+{c1:.6f}*{u}+{c2:.6f}*{u}*{u}+{c3:.6f}*{u}*{u}*{u})"
            out = f"if(lt({T}\\,{b.src:.6f})\\,{poly}\\,{out})"
        return out


@dataclass
class TextLayer:
    text: str
    start: float
    dur: float
    style: str = "chrome_red"   # chrome_red | impact_white
    x: float = 0.5              # centre, share of frame width
    y: float = 0.45
    size: float = 0.22          # cap height, share of frame height
    tilt: float = 0.0           # degrees of in-plane rotation
    yaw: float = 0.0            # perspective turn, -1..1
    enter: str = "letters"      # letters | slam
    exit: str = "flicker"       # flicker | fade | through
    track: float = 0.8          # how much it follows the footage's motion (0 = static)


@dataclass
class Sfx:
    name: str                   # whoosh | hit
    t: float                    # master time it starts
    gain: float = 0.5


@dataclass
class Timeline:
    width: int
    height: int
    fps: int
    source: str
    clips: list[Clip]
    master: dict[str, Curve] = field(default_factory=dict)   # ca, glow, flash, radial, edge, exposure
    reveals: list[dict[str, Any]] = field(default_factory=list)  # {"t", "dur", "mode": "in"|"out"}
    texts: list[TextLayer] = field(default_factory=list)
    sfx: list[Sfx] = field(default_factory=list)
    music: dict[str, Any] = field(default_factory=dict)       # sync reference only, never exported
    notes: list[str] = field(default_factory=list)

    @property
    def duration(self) -> float:
        return max(c.out_end for c in self.clips)

    def to_json(self) -> dict[str, Any]:
        return json.loads(json.dumps(asdict(self)))

    def save(self, path: Path) -> None:
        Path(path).write_text(json.dumps(self.to_json(), indent=1))

    @classmethod
    def load(cls, path: Path) -> "Timeline":
        d = json.loads(Path(path).read_text())
        clips = []
        for c in d.pop("clips"):
            c["keys"] = [TimeKey(**k) for k in c["keys"]]
            for name in ("zoom", "rot", "pan_x", "pan_y"):
                c[name] = Curve(c[name]["keys"])
            c["shakes"] = [Shake(**s) for s in c["shakes"]]
            clips.append(Clip(**c))
        master = {k: Curve(v["keys"]) for k, v in d.pop("master").items()}
        texts = [TextLayer(**t) for t in d.pop("texts")]
        sfx = [Sfx(**s) for s in d.pop("sfx")]
        return cls(clips=clips, master=master, texts=texts, sfx=sfx, **d)

    def check(self) -> list[str]:
        """Problems that would make the render wrong (gaps, overlaps, bad timing)."""
        issues = []
        clips = sorted(self.clips, key=lambda c: c.out_start)
        for a, b in zip(clips, clips[1:]):
            if abs(a.out_end - b.out_start) > 1e-3:
                issues.append(f"{a.label} ends {a.out_end:.3f} but {b.label} starts {b.out_start:.3f}")
        for c in clips:
            if c.keys[0].src != 0 or c.keys[0].out != 0:
                issues.append(f"{c.label}: first key must be (0, 0)")
            if abs(c.keys[-1].src - (c.src_out - c.src_in)) > 1e-3:
                issues.append(f"{c.label}: last key must end at src_out")
            for a, b in zip(c.keys, c.keys[1:]):
                if b.src <= a.src or b.out <= a.out:
                    issues.append(f"{c.label}: keys must move forward ({a} -> {b})")
        return issues
